<h3 id="classroom">Classroom Informática - Florianópolis/SC <span>2008 — 2009</span></h3>
<h4>Desenvolvedor e Instrutor</h4>

<p>Na Classroom, iniciei minha trajetória como desenvolvedor de Adobe Flex, mas logo fui promovido a especialista em Adobe Connect.
    Nessa função, atuei em diversas áreas, incluindo instalação, integração, treinamento, consultoria especializada e suporte técnico para o Adobe Acrobat Connect Pro.
    Além disso, fui responsável por todos os treinamentos relacionados ao Adobe Flex e ao Adobe Acrobat PDF.</p>

<p>Na Classroom aprendi a arte de palestrar o que fiz muitas vezes.
    Aprendi muito de Adobe Flex o que me fez viajar o Brasil palestrando e treinando muitas pessoas.</p>

<p>Já perdi a conta de quantas vezes precisei viajar para São Paulo de última hora. Sempre mantinha uma muda de roupa na mochila, pois saía de casa sem saber se teria que ir para lá.</p>

<p>Minha experiência na Classroom não apenas me desafiou a criar soluções inovadoras, mas também aprimorou minhas habilidades de liderança e minha capacidade de gerenciar projetos complexos e resolver problemas de forma rápida.</p>

<p>Recordo com grande apreço os momentos vividos na Classroom, um ambiente que foi mais do que apenas um local de trabalho:
    foi um espaço de muito crescimento profissional. Infelizmente o proprietário, uma pessoa admirável e inspiradora, teve a perda do pai o que o afetou profundamente, levando-o a um luto avassalador.
    Esse momento de dor e reflexão resultou em uma decisão que, para muitos de nós, foi inesperada e difícil de aceitar:
    o fechamento da empresa que tanto amávamos.</p>
