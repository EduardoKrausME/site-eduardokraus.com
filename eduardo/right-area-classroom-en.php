<h3 id="classroom">Classroom Informática – Florianópolis/SC <span>2008 — 2009</span></h3>
<h4>Developer and Instructor</h4>

<p>At Classroom, I began my journey as an Adobe Flex developer but was soon promoted to Adobe Connect specialist.
    In this role, I worked across multiple areas, including installation, integration, training, specialized consulting, and technical support for Adobe Acrobat Connect Pro.
    Additionally, I was responsible for all training sessions related to Adobe Flex and Adobe Acrobat PDF.</p>

<p>At Classroom, I learned the art of public speaking — something I did many times.
    I deepened my knowledge of Adobe Flex, which led me to travel across Brazil, giving lectures and training many people.</p>

<p>I lost count of how many times I had to travel to São Paulo at the last minute.
    I always kept a change of clothes in my backpack, as I often left home not knowing if I would have to go there.</p>

<p>My experience at Classroom not only challenged me to create innovative solutions but also enhanced my leadership skills and my ability to manage complex projects and solve problems quickly.</p>

<p>I look back with great appreciation on my time at Classroom — a place that was more than just a workplace;
    it was a space of significant professional growth. Unfortunately, the owner, an admirable and inspiring person, suffered the loss of his father, which deeply affected him and led to a period of overwhelming grief.
    That moment of pain and reflection resulted in a decision that, for many of us, was unexpected and hard to accept:
    the closing of the company we all loved so much.</p>
